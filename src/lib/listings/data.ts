/**
 * The seam a real feed would implement. Everything downstream — map, matching,
 * detail pages, the wizard hand-off — consumes this and nothing else.
 */
export interface ListingSource {
  readonly name: string;
  /** True when the inventory is synthetic and must be labelled as such. */
  readonly sample: boolean;
  list(): Listing[];
  get(id: string): Listing | null;
}

export const sampleSource: ListingSource = {
  name: "Sample inventory",
  sample: true,
  list: () => LISTINGS,
  get: (id) => LISTINGS.find((l) => l.id === id) ?? null,
};

export function getListings(): Listing[] {
  return sampleSource.list();
}

export function getListing(id: string): Listing | null {
  return sampleSource.get(id);
}

export function listingsAreSample(): boolean {
  return sampleSource.sample;
}
