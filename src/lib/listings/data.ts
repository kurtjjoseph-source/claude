import type { ParcelInput } from "@/lib/types";

/**
 * Sample listing inventory.
 *
 * IMPORTANT: these are not real parcels and none of them is for sale. There is
 * no public feed of land listings that carries structured water-right data, and
 * inventing plausible-looking listings and presenting them as genuine would be
 * exactly the kind of fabrication this codebase is built to avoid. So the
 * inventory is synthetic, labelled as such everywhere it surfaces, and carries
 * no broker, contact or parcel identifiers that could be mistaken for real.
 *
 * What it is good for is real: it exercises the scoring engine, the match
 * engine and the map end to end, and it defines the shape a live feed would
 * have to produce. Replacing it means implementing `ListingSource` against an
 * MLS, a land brokerage feed or a county records scrape — everything
 * downstream of `getListings()` already works.
 *
 * Coordinates are approximate county centroids, so the pins land in the right
 * county rather than on a specific property.
 */

export interface Listing {
  id: string;
  /** Marketing headline, written the way these listings are actually written. */
  headline: string;
  /** What the parcel actually is, in plain terms. */
  description: string;
  /** The line in the listing that a careful buyer should react to. */
  tell: string;
  lat: number;
  lng: number;
  price: number;
  /** Everything the engine needs to score it. */
  input: ParcelInput;
}

/** Defaults so each listing only states what makes it distinctive. */
function listing(
  id: string,
  headline: string,
  description: string,
  tell: string,
  lat: number,
  lng: number,
  price: number,
  input: Partial<ParcelInput> & Pick<ParcelInput, "jurisdictionCode" | "county" | "acres">,
): Listing {
  return {
    id,
    headline,
    description,
    tell,
    lat,
    lng,
    price,
    input: {
      label: headline,
      intent: "irrigated-crop",
      surfaceRight: "unknown",
      adjudication: "unknown",
      appurtenant: "unknown",
      previouslySevered: "unknown",
      wellStatus: "none",
      aquiferTrend: "unknown",
      inManagedDistrict: "unknown",
      documents: [],
      legalAccess: "unknown",
      mineralEstateSevered: "unknown",
      conservationEasement: "unknown",
      existingLiens: "unknown",
      tribalOrFederalClaimsInBasin: "unknown",
      askingPrice: price,
      buyerCountry: "US",
      ...input,
    },
  };
}

